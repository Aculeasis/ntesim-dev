"""Generate version-matched WASM glue with an isolated closure per engine."""
from pathlib import Path
import os
import subprocess

from tool_output import run_logged

VERSION = "0.2.128"


def generate(root, env, profile="release", verbose=False):
    suffix = ".exe" if os.name == "nt" else ""
    cli = root / "cache/wasm-bindgen/bin" / ("wasm-bindgen" + suffix)
    if not cli.is_file():
        raise RuntimeError(
            f"Install the pinned generator: python tools/cargo.py install wasm-bindgen-cli "
            f"--version {VERSION} --locked --root cache/wasm-bindgen --jobs 4")
    version = subprocess.check_output([str(cli), "--version"], env=env, text=True).strip()
    if version != f"wasm-bindgen {VERSION}":
        raise RuntimeError(f"WASM generator mismatch: {version}; expected {VERSION}")
    output = root / ("target/wasm-bindgen-profiling" if profile == "profiling" else "target/wasm-bindgen")
    source = root / f"target/wasm32-unknown-unknown/{profile}/ntesim_wasm.wasm"
    debug_args = ["--keep-debug"] if profile == "profiling" else []
    status = run_logged([str(cli), str(source), "--target", "no-modules", "--out-dir", str(output),
                         "--out-name", "ntesim_wasm", "--omit-default-module-path", *debug_args],
                        cwd=root, env=env, label="wasm-bindgen", verbose=verbose)
    if status:
        return status
    wasm_file = output / "ntesim_wasm_bg.wasm"
    wasm_opt = root / "cache/wasm-opt/bin" / ("wasm-opt" + suffix)
    opt_bin = str(wasm_opt) if wasm_opt.is_file() else (subprocess.run(["where.exe" if os.name == "nt" else "which", "wasm-opt"], capture_output=True, text=True).stdout.strip().splitlines()[0] if subprocess.run(["where.exe" if os.name == "nt" else "which", "wasm-opt"], capture_output=True).returncode == 0 else None)
    if opt_bin and wasm_file.is_file() and profile in ("release", "profiling"):
        debug_args = ["-g"] if profile == "profiling" else []
        status = run_logged([opt_bin, "-O3", *debug_args, str(wasm_file), "-o", str(wasm_file)], cwd=root, env=env, label="wasm-opt", verbose=verbose)
        if status:
            return status
    # The no-modules generator contains its own imports, initialization and
    # ownership glue. Nest the unmodified output to avoid sharing its singleton
    # across multiple engines in the same Worker/Node process.
    script = (output / "ntesim_wasm.js").read_text(encoding="utf-8")
    factory = ("// Generated by tools/wasm_bindings.py; do not edit.\n"
               "function createBindings() {\n" + script + "\nreturn wasm_bindgen;\n}\n"
               "globalThis.NtesimCreateBindings = createBindings;\n"
               "if (typeof module !== 'undefined' && module.exports) module.exports = { createBindings };\n")
    (output / "bindings.js").write_text(factory, encoding="utf-8")
    return 0
